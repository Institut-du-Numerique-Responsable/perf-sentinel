// French typography: a no-break space before : ? ! so the sign never starts a line.
const frenchSpacing = (o) => {
  for (const [k, v] of Object.entries(o)) {
    if (typeof v === 'string') o[k] = v.replace(/ ([:?!])/g, '\u00a0$1');
    else frenchSpacing(v);
  }
};
frenchSpacing(COPY.fr);
